/**
 * Static HTML report for the weekly health scan — no template engine needed.
 * Green/amber/red status per site, broken-link details, visual-diff column.
 */
export function renderReport(results) {
  const rows = results.map((r) => {
    const cls = !r.ok ? 'down' : r.brokenLinks.length || r.visualPct ? 'warn' : 'ok';
    const links = r.brokenLinks.map((b) => `<li><code>${esc(b.url)}</code> → ${b.status}</li>`).join('') || '<li class="ok">none</li>';
    const visual = r.firstRun ? 'baseline set' : r.visualPct ? `${r.visualPct}% changed` : 'stable';
    return `<tr class="${cls}">
      <td><a href="${esc(r.url)}">${esc(r.name)}</a></td>
      <td>${r.ok ? `UP ${r.status}` : `DOWN ${r.status || 'ERR'}`}</td>
      <td>${r.ms} ms</td>
      <td><ul>${links}</ul></td>
      <td>${visual}</td>
    </tr>`;
  }).join('\n');

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Site Health Report</title>
<style>
 body{font-family:system-ui,sans-serif;margin:2rem;color:#1c2733}
 table{border-collapse:collapse;width:100%}
 th,td{border:1px solid #d7dee6;padding:.5rem .75rem;text-align:left;vertical-align:top}
 tr.ok td{background:#f4fbf6}tr.warn td{background:#fff9ec}tr.down td{background:#fdf0ef}
 ul{margin:0;padding-left:1.1rem}.ok{color:#2e7d32}
 footer{margin-top:1rem;color:#667380;font-size:.85rem}
</style></head><body>
<h1>Site Health Report</h1>
<p>${results.length} site(s) scanned on ${new Date().toISOString().slice(0, 10)}.</p>
<table><thead><tr><th>Site</th><th>Uptime</th><th>Response</th><th>Broken links</th><th>Visual diff</th></tr></thead>
<tbody>${rows}</tbody></table>
<footer>Generated by playwright-flow-kit / Site Health Auditor.</footer>
</body></html>`;
}

function esc(value) {
  return String(value).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
